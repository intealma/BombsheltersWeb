"""Build the Beredskap database seed from the existing shelter pipeline.

Reads skyddsrum_enriched.geojson (output of fetch_shelters_municipality.py,
gitignored, about 40 MB) and writes SQL seed files that `supabase db reset`
loads:

    supabase/seed/10_kommuner.sql   every kommun that appears in the data
    supabase/seed/20_shelters.sql   shelters in the chosen län

The public shelters.geojson is not touched.

Usage (PowerShell, from the beredskap folder):

    python scripts/build_shelter_seed.py                  # Östergötland (län 05)
    python scripts/build_shelter_seed.py --lan 05 06      # several län
    python scripts/build_shelter_seed.py --lan all        # all of Sweden
"""

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEREDSKAP = HERE.parent
DEFAULT_SOURCE = BEREDSKAP.parent / "skyddsrum_enriched.geojson"
SEED_DIR = BEREDSKAP / "supabase" / "seed"

# Same bounds the public map is restricted to, with a small margin.
LON_MIN, LON_MAX = 10.0, 24.5
LAT_MIN, LAT_MAX = 55.0, 69.5

ID_RE = re.compile(r"^[0-9A-Za-z-]{1,32}$")
KOMMUN_RE = re.compile(r"^[0-9]{4}$")

# Kommuner with no shelters in the MCF data still need to exist, so their
# kommun organisation can be created and shows 0 shelters instead of failing.
EXTRA_KOMMUNER = {
    "0509": "Ödeshög",
    "0512": "Ydre",
}


def sql_str(value):
    return "'" + str(value).replace("'", "''") + "'"


def point_from_geometry(geom):
    """Return (lon, lat) from a Point or single-point MultiPoint, or raise.

    The WFS delivers MultiPoint with one point. trim_for_web.py has written
    that as a Point with double-nested coordinates before, which MapLibre
    silently rejects, so both shapes are accepted here and anything else
    fails loudly.
    """
    if not geom:
        raise ValueError("missing geometry")
    gtype, coords = geom.get("type"), geom.get("coordinates")
    if gtype == "MultiPoint" or (gtype == "Point" and coords and isinstance(coords[0], list)):
        if len(coords) != 1:
            raise ValueError(f"{gtype} with {len(coords)} points")
        coords = coords[0]
    elif gtype != "Point":
        raise ValueError(f"unsupported geometry type {gtype}")
    if len(coords) < 2 or not all(isinstance(c, (int, float)) for c in coords[:2]):
        raise ValueError(f"bad coordinates {coords!r}")
    lon, lat = float(coords[0]), float(coords[1])
    if not (LON_MIN <= lon <= LON_MAX and LAT_MIN <= lat <= LAT_MAX):
        raise ValueError(f"outside Sweden: {lon}, {lat}")
    return lon, lat


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--lan", nargs="+", default=["05"], help="län codes, or 'all'")
    args = parser.parse_args()

    if not args.source.exists():
        sys.exit(f"Source not found: {args.source}\nRun fetch_shelters.py and fetch_shelters_municipality.py first.")

    with args.source.open(encoding="utf-8") as f:
        features = json.load(f)["features"]

    all_lan = args.lan == ["all"]
    wanted = set(args.lan)
    kommuner = dict(EXTRA_KOMMUNER)
    rows, errors, seen = [], Counter(), set()

    for feat in features:
        p = feat.get("properties") or {}
        sid = str(p.get("name") or "").strip()
        kod = str(p.get("KnKod") or "").strip()
        namn = str(p.get("KnNamn") or "").strip()

        if KOMMUN_RE.match(kod) and namn:
            kommuner.setdefault(kod, namn)
        if not (all_lan or kod[:2] in wanted):
            continue

        try:
            if not ID_RE.match(sid):
                raise ValueError(f"bad id {sid!r}")
            if sid in seen:
                raise ValueError(f"duplicate id {sid}")
            if not KOMMUN_RE.match(kod):
                raise ValueError(f"bad kommun code {kod!r}")
            lon, lat = point_from_geometry(feat.get("geometry"))
            capacity = p.get("numberofoccupants") or 0
            if not isinstance(capacity, int) or capacity < 0:
                raise ValueError(f"bad capacity {capacity!r}")
        except ValueError as e:
            errors[str(e).split(":")[0]] += 1
            continue

        seen.add(sid)
        address = str(p.get("additionallocationdescription") or "").strip()
        rows.append((sid, str(p.get("inspireid") or "").strip() or None, address, capacity, kod, lon, lat))

    if errors:
        print("Skipped invalid features:", dict(errors))
    if not rows:
        sys.exit("No shelters matched; check --lan.")

    SEED_DIR.mkdir(parents=True, exist_ok=True)

    with (SEED_DIR / "10_kommuner.sql").open("w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by scripts/build_shelter_seed.py. Do not edit by hand.\n")
        f.write("-- Kommun codes and names from SCB, as joined onto the MCF shelter data.\n")
        f.write("insert into public.kommuner (kod, namn, lan_kod) values\n")
        f.write(",\n".join(f"  ({sql_str(k)}, {sql_str(v)}, {sql_str(k[:2])})" for k, v in sorted(kommuner.items())))
        f.write("\non conflict (kod) do update set namn = excluded.namn;\n")

    rows.sort()
    label = "all län" if all_lan else "län " + ", ".join(sorted(wanted))
    with (SEED_DIR / "20_shelters.sql").open("w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by scripts/build_shelter_seed.py. Do not edit by hand.\n")
        f.write(f"-- Public MCF/MSB shelter data ({label}): {len(rows)} shelters.\n")
        f.write("-- The id is the MCF shelter number, the same key the public map uses.\n")
        for i in range(0, len(rows), 500):
            chunk = rows[i:i + 500]
            f.write("insert into public.shelters (id, inspire_id, address, capacity, kommun_kod, lon, lat) values\n")
            f.write(",\n".join(
                f"  ({sql_str(sid)}, {sql_str(iid) if iid else 'null'}, {sql_str(addr)}, {cap}, {sql_str(kod)}, {lon:.7f}, {lat:.7f})"
                for sid, iid, addr, cap, kod, lon, lat in chunk
            ))
            f.write("\non conflict (id) do update set inspire_id = excluded.inspire_id, address = excluded.address,\n"
                    "  capacity = excluded.capacity, kommun_kod = excluded.kommun_kod, lon = excluded.lon, lat = excluded.lat;\n")

    per_kommun = Counter(r[4] for r in rows)
    print(f"Wrote {len(kommuner)} kommuner and {len(rows)} shelters ({label}).")
    for kod, n in sorted(per_kommun.items()):
        print(f"  {kod} {kommuner.get(kod, '?'):<14} {n:>6}")


if __name__ == "__main__":
    main()
